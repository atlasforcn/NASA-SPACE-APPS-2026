import { chromium } from '@playwright/test';
import { spawn } from 'node:child_process';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const server = spawn(process.execPath,['node_modules/vite/bin/vite.js','--mode','test','--host','127.0.0.1','--port','5192','--strictPort'],{stdio:'pipe'});
let browser;
try {
  await new Promise((resolve,reject) => { server.stdout.on('data',data => { if (data.toString().includes('5192')) resolve(); }); server.on('exit',code => reject(Error(`Vite exited ${code}`))); setTimeout(()=>reject(Error('Vite timeout')),15000).unref(); });
  browser = await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page = await browser.newPage({viewport:{width:1440,height:1000}}), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:5192');
  await page.waitForFunction(()=>window.__mission?.state.ready);
  await page.locator('#pick-start').click();
  const box = await page.locator('#map').boundingBox();
  await page.locator('#map').click({position:{x:box.width/2,y:box.height/2}});
  await page.waitForFunction(()=>window.__mission.state.hasStart);
  await page.evaluate(()=>{
    const s=window.__mission.state;
    s.targets=[{id:'stop-a',name:'科學站 A',x:-1900,y:-800,unit:'測試'},{id:'stop-b',name:'科學站 B',x:-2200,y:-800,unit:'測試'},{id:'goal',name:'終點',x:-2400,y:-800,unit:'測試'}];
    s.destination='stop-a';
  });
  await page.locator('#add-stop').click();
  await page.locator('#destination').selectOption('stop-b');
  await page.locator('#add-stop').click();
  await page.getByRole('button',{name:'上移第 2 站',exact:true}).click();
  assert.deepEqual(await page.evaluate(()=>[...window.__mission.state.stopIds]),['stop-b','stop-a']);
  await page.getByRole('button',{name:'移除第 1 站',exact:true}).click();
  await page.locator('#destination').selectOption('goal');
  await page.locator('#round-trip').check();
  await page.locator('#time-budget').fill('0.01');
  await page.locator('#plan').click();
  await page.waitForFunction(()=>window.__mission.state.routeOptions?.safer.reachable);
  assert.equal(await page.locator('.itinerary li').count(),3);
  assert((await page.locator('.route-comparison').innerText()).includes('超出'));
  await page.locator('#choose-shortest').click();
  assert.equal(await page.evaluate(()=>window.__mission.state.selectedRoute),'shortest');
  assert(await page.locator('#choose-shortest').getAttribute('aria-pressed')==='true');
  await page.getByRole('checkbox',{name:'比較不同路線'}).check();
  await page.waitForFunction(()=>window.__mission.state.profileLegend.some(v=>v.name==='較低風險路線'));
  const downloadPromise=page.waitForEvent('download');
  await page.locator('#export-plan').click();
  const download=await downloadPromise;
  const exported=JSON.parse(await fs.readFile(await download.path(),'utf8'));
  assert.equal(exported.properties.body,'Mars');
  assert.equal(exported.features[0].properties.mode,'shortest');
  const points=exported.features[0].geometry.coordinates;
  assert.deepEqual(points[0],points.at(-1));
  await page.locator('#fit-plan').click();
  await page.locator('.route-comparison').screenshot({path:'test-results/route-planner-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('.route-comparison').scrollIntoViewIfNeeded();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:'test-results/route-planner-mobile.png'});
  await page.locator('#risk-weight').fill('3');
  await page.waitForFunction(()=>window.__mission.state.route===null && window.__mission.state.routeOptions===null);
  assert(await page.locator('#simulate').isDisabled());
  assert.deepEqual(errors,[]);
  console.log('Planner UI: ordered stops, removal, return, dual routes, switching, budgets, profiles, GeoJSON, mobile and invalidation passed');
} finally {
  await browser?.close();
  server.kill();
}
