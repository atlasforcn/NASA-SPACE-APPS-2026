import assert from 'node:assert/strict';
import C from '../core.mjs';
import P from '../planet.mjs';
import {buildItinerary,measureRoute} from '../src/routePlanner.mjs';
import {createNavigationContext,createGeologyIndex,geoDistance} from '../src/navigation-context.mjs';
const o={geologyEnabled:true,thermalEnabled:false,sandFactor:1.8,rockFactor:1.25,unknownFactor:1.1,thermalThreshold:200,thermalFactor:1.2};
const feature=(unit,rings)=>({properties:{unit,name:'Test material'},rings});
const ring=[[-300,-600],[300,-600],[300,600],[-300,600]];
const index=createGeologyIndex({features:[feature('7',[ring])]});
const toGeo=(x,y)=>({lat:18.44+y/3396190*180/Math.PI,lng:77.42+x/3396190/Math.cos(18.44*Math.PI/180)*180/Math.PI});
const thermal={meta:{kind:'raster',width:1,height:1},values:new Float32Array([100])};
const context=createNavigationContext({options:o,geologyIndex:index,toGeo});
assert.equal(context.sample(0,0).factor,1.8);
assert.equal(context.sample(1000,0).unknown,true);
assert.equal(context.sample(1000,0).blocked,false);
const combined=createNavigationContext({options:{...o,thermalEnabled:true,thermalFactor:2},geologyIndex:index,thermal,toGeo});
assert.equal(combined.sample(0,0).factor,2); // max, not 1.8 * 2
assert.equal(combined.sample(1,1).factor,combined.sample(2,2).factor);
assert.equal(createNavigationContext({options:{...o,geologyEnabled:false,thermalEnabled:false},toGeo}).sample(0,0).factor,1);
assert.equal(createNavigationContext({options:{...o,thermalEnabled:true},geologyIndex:[],thermal:{...thermal,values:new Float32Array([NaN])},toGeo}).sample(0,0).unknown,true);
assert.throws(()=>createNavigationContext({options:{...o,sandFactor:.5},toGeo}));
const zone={...toGeo(0,0),name:'Image exclusion',radius:12};
const blocked=createNavigationContext({options:o,zones:[zone],toGeo});
assert(blocked.sample(0,0).blocked);
assert(blocked.segmentBlocked({x:-100,y:0},{x:100,y:0}));
assert(!blocked.segmentBlocked({x:-100,y:100},{x:100,y:100}));
assert(geoDistance({lat:0,lng:179.99},{lat:0,lng:-179.99})<1200);
const acrossSeam=createNavigationContext({options:o,zones:[{lat:0,lng:179.99,radius:1500,name:'Seam'}],toGeo:(x,y)=>({lat:y,lng:x})});
assert(acrossSeam.sample(-179.99,0).blocked);
const grid={schema:'mars-local-grid-v1',crs:'MARS_EQ_LOCAL_TANGENT',origin:{lat:18.44,lng:77.42},width:61,height:61,xMin:-3000,xMax:3000,yMin:-3000,yMax:3000,heights:Array(61*61).fill(0),source:{url:'https://example.invalid/navigation-test'}};
C.setDEM(grid);C.setSlopeLimit(24);C.setRoughnessLimit(1);
C.setNavigationContext(createNavigationContext({options:{...o,sandFactor:5,unknownFactor:1},geologyIndex:index,toGeo:(x,y)=>C.localToLatLng(x,y)}));
const start={x:-2000,y:0},goal={x:2000,y:0,name:'Goal'};
const routes=buildItinerary(start,[goal],{riskWeight:5});
assert(routes.energy.reachable&&routes.safer.reachable&&routes.shortest.reachable);
assert(routes.energy.energy<routes.shortest.energy);
assert(routes.energy.surface>routes.shortest.surface);
assert(routes.shortest.materialEnergy>0);
assert(routes.shortest.navigationReasons.some(c=>c.reason.includes('地質')));
assert(Math.abs(routes.energy.energy-measureRoute(routes.energy.path).energy)<1e-6);
C.setNavigationContext(blocked);
assert(!C.segmentSafe({x:-100,y:0},{x:100,y:0}));
const detour=buildItinerary(start,[goal]);
for(const route of Object.values(detour))assert(route.reachable&&route.path.every((p,i,path)=>!i||C.segmentSafe(path[i-1],p)));
const reject=buildItinerary(start,[{x:0,y:0,name:'Blocked centre'}]);
for(const route of Object.values(reject))assert(!route.reachable);
// Geographically anchored circles and Jezero materials survive active-frame changes.
C.setDEM({...grid,origin:{lat:18.45,lng:77.43}});
C.setNavigationContext(createNavigationContext({options:o,zones:[zone],geologyIndex:index,toGeo:(x,y)=>C.localToLatLng(x,y)}));
const reprojected=C.latLngToLocal(zone.lat,zone.lng);
assert(C.risk(reprojected.x,reprojected.y).blocked);
C.setNavigationContext(null);C.clearDEM();
console.log('Navigation materials, no double counting, unknown coverage, narrow exclusions, seam, frame changes and route detours passed');
